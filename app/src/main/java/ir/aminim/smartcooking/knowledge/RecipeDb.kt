    /** مواد با قالب «id=مقدار؛ …»؛ «?» یعنی اختیاری و «~نام» یعنی ماده آزاد */
    private fun ings(spec: String): List<RecipeIng> = spec.split(';').map { it.trim() }.filter { it.isNotEmpty() }.map { part ->
        val opt = part.startsWith("?")
        val p = part.removePrefix("?")
        val key = p.substringBefore('=').trim()
        val amount = p.substringAfter('=', "").trim()
        if (key.startsWith("~")) RecipeIng(key.drop(1), amount, "", opt)
        else RecipeIng(Ingredients.byId(key)?.fa ?: key, amount, key, opt)
    }

