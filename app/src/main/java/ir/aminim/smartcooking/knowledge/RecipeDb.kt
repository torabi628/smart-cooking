    private val byIdMap by lazy { all.associateBy { it.id } }
    fun byId(id: String): Recipe? = byIdMap[id]

    fun search(q: String): List<Recipe> {
        val n = Ingredients.norm(q)
        if (n.isBlank()) return all
        return all.filter { r ->
            Ingredients.norm(r.name).contains(n) || Ingredients.norm(r.desc).contains(n) ||
                r.ingredients.any { Ingredients.norm(it.name).contains(n) } || r.tags.any { Ingredients.norm(it).contains(n) }
        }
    }

    /** پیدا کردن نزدیک‌ترین دستور داخلی بر اساس نام (برای کامل کردن پیشنهادهای هوش مصنوعی) */
    fun matchName(name: String): Recipe? {
        val n = Ingredients.norm(name)
        if (n.length < 3) return null
        return all.firstOrNull { Ingredients.norm(it.name) == n } ?: all.firstOrNull { val m = Ingredients.norm(it.name); m.contains(n) || n.contains(m) }
    }
